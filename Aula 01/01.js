// Concatenar: + | Separar: , 
// O + é mais utilizado para concatenar, ou seja, juntar as informações em uma única string. Já a vírgula (,) é usada para separar os valores e imprimir cada um deles de forma independente, sem concatenar.

// Tipagem
let valor;

console.log("Valor: ", valor, " | Tipo: ", typeof(valor));

valor = 10;

console.log("Valor: ", valor, " | Tipo: ", typeof(valor));

valor = 'Lucas';

console.log("Valor: ", valor, " | Tipo: ", typeof(valor));

valor = true;

console.log("Valor: ", valor, " | Tipo: ", typeof(valor));

valor = null;

console.log("Valor: ", valor, " | Tipo: ", typeof(valor));