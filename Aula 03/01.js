// variável de controle
// Condição
// Incremento/Decremento

// for é uma estrutura de repetição que é composta por três partes: a variável de controle, a condição e o incremento/decremento. Ela é utilizada para executar um bloco de código um número específico de vezes.

// Utilizando o for, dentro dos parênteses, temos a variável de controle, que é inicializada com um valor. Em seguida, temos a condição, que é avaliada antes de cada iteração do loop. Se a condição for verdadeira, o bloco de código dentro do loop será executado. Por fim, temos o incremento/decremento, que é executado após cada iteração do loop.
for (let contador = 0; contador < 5; contador++) {
    console.log("Olá, mundo!");
}