// Exemplo: Recebe dois números(parâmetro) e retorna a soma dos números digitados.

function somar(num1, num2) { // Declaração da função, onde num1 e num2 são os parâmetros da função.
    return num1 + num2;
}

let soma = somar (2, 3); // Chamada da função, onde 2 e 3 são os argumentos da função. O resultado da soma é 5.

console.log("A sima é ", soma); // Imprime o resultado da soma, que é 5.
// Esta é uma função com parâmetro e retorno.


