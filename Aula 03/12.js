// Função Anônima: é uma função que não possui um nome. Ela é utilizada quando queremos criar uma função de forma rápida e não precisamos reutilizá-la em outros lugares do código. As funções anônimas são frequentemente utilizadas como argumentos para outras funções, como callbacks.

const somar = function (num1, num2) {
    return num1 + num2;
}

somar(2, 3); // O resultado da soma é 5.

// Esta é uma função anônima, pois ela não possui um nome. Ela é atribuída a uma variável chamada somar, que pode ser utilizada para chamar a função. A função recebe dois parâmetros, num1 e num2, e retorna a soma dos dois números.