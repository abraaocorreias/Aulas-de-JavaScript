let contador = 0; // variável de controle

do {
    console.log("Olá, mundo!");
    contador++; // incremento
} while (contador < 5);

// do...while é uma estrutura de repetição que é composta por duas partes: o bloco de código e a condição. Ela é utilizada para executar um bloco de código pelo menos uma vez, e depois repetir a execução do bloco enquanto a condição for verdadeira. A diferença entre o do...while e o while é que o do...while executa o bloco de código antes de avaliar a condição, enquanto o while avalia a condição antes de executar o bloco de código. No exemplo acima, o bloco de código dentro do do...while será executado pelo menos uma vez, e depois a condição contador < 5 será avaliada. Se a condição for verdadeira, o bloco de código será executado novamente, e assim por diante, até que a condição seja falsa.

