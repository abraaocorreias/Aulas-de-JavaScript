//Arrays 


//Lista de Valores

//Declaração de um Array
const numeros = [];

//Atribuição de Valores
numeros[0] = 1;
numeros[1] = 2;
numeros[2] = 3;


//Acessando os Valores
console.log(numeros); //Imprime o Array completo
console.log(numeros[0]); //Acessando o primeiro elemento do Array
console.log(numeros[1]); //Acessando o segundo elemento do Array
console.log(numeros[2]); //Acessando o terceiro elemento do Array

//Manipulação de Arrays
numeros[0] = 0; //Alterando o valor do primeiro elemento do Array
console.log(numeros); //Imprime o Array atualizado

//Inicialização de um Array com Valores

const notas = [7.6, 4.5, 8.7];
console.log(notas); //Imprime o Array completo

